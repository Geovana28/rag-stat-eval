"""
CLI Runner for RAG Statistical Evaluation Suite
Usage:
    python run_eval.py --samples 500 --json web/benchmark_data.json --report REPORT.md
"""

import os
import sys
import json
import argparse
from pipeline.evaluator import run_full_statistical_evaluation

def generate_markdown_report(data: dict) -> str:
    summary = data["summary"]
    meta = data["metadata"]
    p1 = data["pillar1_calibration"]
    p2 = data["pillar2_hypothesis_testing"]
    p3 = data["pillar3_robustness_curves"]
    p4 = data["pillar4_fairness_audit"]
    
    md = f"""# 📊 Statistical Evaluation & Robustness Stress Test Report
**Evaluation Date**: Automated Run  
**Evaluated Samples**: {meta['total_benchmark_samples']} items across domains ({', '.join(meta['domains_evaluated'])})  
**Baseline Model**: {meta['baseline_model']}  
**Champion Model**: {meta['champion_model']}  

---

## 🚀 Executive Summary & Statistical Verification

| Metric | Baseline | Champion | Variance / Effect | Statistical Status |
|---|---|---|---|---|
| **Accuracy (Exact Match / Verification)** | {summary['baseline_accuracy']}% | {summary['champion_accuracy']}% | **+{summary['accuracy_lift_pct']}% Lift** | **Significant** (p = {summary['p_value_mcnemar']:.2e}) |
| **ECE (Expected Calibration Error)** | {summary['baseline_ece']} | {summary['champion_ece']} | **-{summary['ece_reduction_pct']}% Calibration Gap** | Calibrated Probabilities |
| **Brier Loss** | {p1['baseline']['brier_score']} | {p1['champion']['brier_score']} | -{p1['baseline']['brier_score'] - p1['champion']['brier_score']:.4f} | Lower Prediction Error |
| **Disparate Impact Ratio (DIR)** | — | {p4['disparate_impact_ratio']} | Threshold ≥ 0.80 | {'✅ Compliant' if p4['passes_four_fifths_rule'] else '⚠️ Disparity Warning'} |

---

## 1. 🎯 Uncertainty Calibration & Reliability Analysis
- **Baseline Model ECE**: `{p1['baseline']['ece']}` | **MCE**: `{p1['baseline']['mce']}` (Suffers from uncalibrated overconfidence on hallucinated/incorrect queries)
- **Champion Model ECE**: `{p1['champion']['ece']}` | **MCE**: `{p1['champion']['mce']}` (Probability scores strictly correlate with real correctness likelihood)

---

## 2. 🧪 Hypothesis Testing & Significance Proof
- **McNemar's Chi-Square Test**:
  - $\\chi^2$ Statistic: `{p2['mcnemar']['statistic']}`
  - $p$-value: `{p2['mcnemar']['p_value']:.4e}`
  - **Verdict**: {p2['mcnemar']['interpretation']}
- **Paired Bootstrap Resampling (2,000 resamples)**:
  - Observed Difference: `+{p2['paired_bootstrap']['observed_diff'] * 100:.2f}%`
  - 95% Confidence Interval: `[{p2['paired_bootstrap']['ci_95_lower'] * 100:.2f}%, {p2['paired_bootstrap']['ci_95_upper'] * 100:.2f}%]`
  - Null Hypothesis ($H_0: \\Delta = 0$) rejected with $p = {p2['paired_bootstrap']['p_value']:.4f}$.
- **Wilcoxon Signed-Rank Test (Semantic Alignment Score)**:
  - Cohen's d: `{p2['wilcoxon']['cohens_d']}` (Magnitude: *{p2['wilcoxon']['effect_size_magnitude']}*)

---

## 3. 🛡️ Noise Fragility & Adversarial Perturbation
Retention of performance under progressive typographical, synonym, and distractor noise:
- At **10% perturbation**: Baseline retains `{p3['baseline_curve'][2]['retention_rate']}%` vs Champion retaining `{p3['champion_curve'][2]['retention_rate']}%`.
- At **35% perturbation**: Baseline drops to `{p3['baseline_curve'][4]['performance'] * 100:.1f}%` accuracy while Champion preserves `{p3['champion_curve'][4]['performance'] * 100:.1f}%`.

---

## 4. ⚖️ Fairness & Demographic Disparity Audit
- **Subgroups Audited**: {', '.join(meta['subgroups_audited'])}
- **Disparate Impact Ratio**: `{p4['disparate_impact_ratio']}` (US EEOC 4/5ths / 80% Rule)
- **Demographic Parity Difference**: `{p4['demographic_parity_difference'] * 100:.1f}%`
- **Equal Opportunity Difference**: `{p4['equal_opportunity_difference'] * 100:.1f}%`
- **Audit Verdict**: *{p4['verdict']}*

---
*Generated by RAG Statistical Evaluation Suite (Production ML Governance & Statistical Stress-Testing).*
"""
    return md

def main():
    parser = argparse.ArgumentParser(description="Run RAG Statistical Evaluation Suite")
    parser.add_argument("--samples", type=int, default=500, help="Number of benchmark samples to evaluate")
    parser.add_argument("--json", type=str, default="web/benchmark_data.json", help="Path to save JSON results")
    parser.add_argument("--report", type=str, default="STATISTICAL_EVAL_REPORT.md", help="Path to save Markdown report")
    args = parser.parse_args()
    
    # Safe UTF-8 console output on Windows
    if sys.platform == "win32":
        try:
            sys.stdout.reconfigure(encoding='utf-8')
        except Exception:
            pass
            
    print(f"[+] Running comprehensive statistical evaluation across {args.samples} samples...")
    results = run_full_statistical_evaluation(n_samples=args.samples)
    
    # Save JSON
    json_path = os.path.abspath(args.json)
    os.makedirs(os.path.dirname(json_path), exist_ok=True)
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2, ensure_ascii=False)
    print(f"[OK] Saved interactive JSON payload: {json_path}")
    
    # Save Markdown report
    report_path = os.path.abspath(args.report)
    md_content = generate_markdown_report(results)
    with open(report_path, 'w', encoding='utf-8') as f:
        f.write(md_content)
    print(f"[OK] Generated executive evaluation report: {report_path}")
    
    # Print terminal summary
    summary = results["summary"]
    print("\n" + "="*60)
    print("STATISTICAL EVALUATION SUMMARY")
    print("="*60)
    print(f"Baseline Accuracy:  {summary['baseline_accuracy']}% (ECE: {summary['baseline_ece']})")
    print(f"Champion Accuracy:  {summary['champion_accuracy']}% (ECE: {summary['champion_ece']})")
    print(f"Accuracy Lift:      +{summary['accuracy_lift_pct']}% (p-val: {summary['p_value_mcnemar']:.2e})")
    print(f"Hypothesis Test:    Significant (p < 0.05) = {summary['statistically_significant']}")
    print(f"Fairness (80% DIR): {summary['fairness_four_fifths_compliant']}")
    print("="*60 + "\n")

if __name__ == "__main__":
    main()
